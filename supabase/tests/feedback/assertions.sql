-- Runs only against the disposable database created by the test script.
create function public.test_assert(ok boolean, message text) returns void
language plpgsql as $$ begin
  if ok is distinct from true then raise exception 'FAIL: %', message; end if;
end $$;

-- The diff engine omits grants, so verify the explicit privilege supplement.
select test_assert(
  not has_function_privilege('anon', 'public.prepare_feedback_message()', 'execute')
  and not has_function_privilege('authenticated', 'public.prepare_feedback_message()', 'execute'),
  'trigger function is not directly executable by client roles');

set role authenticated;
set test.uid = '00000000-0000-0000-0000-000000000007';
select submit_feedback('Owner thread');
set test.uid = '00000000-0000-0000-0000-000000000008';
select submit_feedback('Other user thread');
set test.uid = '00000000-0000-0000-0000-000000000002';
insert into feedback_messages(feedback_id, author_id, body, attachment_paths)
values (1, 2, 'Admin attachment', array['2/shared.png']),
       (2, 2, 'Private to another thread', array['2/private.png']);
reset role;
insert into storage.objects values
 ('feedback-attachments', '2/shared.png'),
 ('feedback-attachments', '2/private.png'),
 ('feedback-attachments', '2/unlinked.png'),
 ('other-bucket', '2/shared.png');

set role authenticated;
set test.uid = '00000000-0000-0000-0000-000000000007';
-- Trying to reference another author's object must not grant access to it.
insert into feedback_messages(feedback_id, author_id, body, attachment_paths)
values (1, 7, 'Forged attachment reference', array['2/private.png']);
select test_assert((select count(*) = 1 from storage.objects),
 'owner reads exactly the admin attachment in their own thread');
select test_assert(exists(select 1 from storage.objects where name = '2/shared.png'),
 'admin attachment is readable by the owner');

-- The client must not control message timestamps in either direction.
insert into feedback_messages(feedback_id, author_id, body, created_at)
values (1, 7, 'Future timestamp', '2099-01-01'),
       (1, 7, 'Past timestamp', '2000-01-01');
select test_assert((select bool_and(created_at between now() - interval '1 minute' and clock_timestamp())
 from feedback_messages where body in ('Future timestamp', 'Past timestamp')),
 'message timestamps are generated by the server');
set test.uid = '00000000-0000-0000-0000-000000000002';
select mark_feedback_read(1);
select mark_feedback_read(2);
select test_assert(admin_unread_feedback_count() = 0, 'mark read clears the admin badge');
insert into feedback_messages(feedback_id, author_id, body, created_at)
values (1, 2, 'Admin future timestamp', '2099-01-01');
set test.uid = '00000000-0000-0000-0000-000000000007';
select mark_feedback_read(1);
select test_assert(unread_feedback_count() = 0, 'mark read clears the owner badge');

reset role;
update feedback set status = 'reviewed' where id = 1;
update feedback set status = 'dismissed' where id = 2;
set role authenticated;
set test.uid = '00000000-0000-0000-0000-000000000002';
do $$ declare thread_id integer; begin
  foreach thread_id in array array[1, 2] loop
    begin
      insert into feedback_messages(feedback_id, author_id, body)
      values (thread_id, 2, 'Must not post after closure');
      raise exception 'FAIL: admin posted into a closed thread';
    exception when insufficient_privilege then null;
    end;
  end loop;
end $$;
set test.uid = '00000000-0000-0000-0000-000000000007';
do $$ begin
  begin
    insert into feedback_messages(feedback_id, author_id, body)
    values (1, 7, 'Owner must not post after closure');
    raise exception 'FAIL: owner posted into a closed thread';
  exception when insufficient_privilege then null;
  end;
end $$;
select 'Feedback security assertions passed' as result;
